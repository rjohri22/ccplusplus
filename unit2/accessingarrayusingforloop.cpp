#include <iostream>
using namespace std;

int main()
{
    // Declare and initialize an integer array.
    int numbers[5] = {10, 20, 30, 40, 50};

    // Use a for loop to access each array element.
    for (int i = 0; i < 5; i++)
    {
        // Print the element at index i.
        cout << numbers[i] << endl;
    }

    return 0;
}