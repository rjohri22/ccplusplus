#include <stdio.h>

int main()
{
    // Start the loop variable i with 1.
    // Continue while i is less than or equal to 5.
    // Increase i by 1 after every iteration.
    for (int i = 1; i <= 5; i++)
    {
        // Print the current value of i.
        printf("%d\n", i);
    }

    return 0;
}