#include <stdio.h>

int main()
{
    // Stores a whole number.
    int age = 25;

    // Stores a decimal number.
    float marks = 85.5;

    // Stores a single character.
    char grade = 'A';

    printf("Age = %d\n", age);
    printf("Marks = %.1f\n", marks);
    printf("Grade = %c\n", grade);

    return 0;
}