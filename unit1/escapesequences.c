#include <stdio.h>

int main()
{
    // \n is an escape sequence.
    // It moves the cursor to the next line.
    printf("Hello\nStudents");

      // \n moves the output to a new line.
    printf("Name: Rohit\n");

    // \t inserts a tab space between the two words.
    printf("Age:\t25\n");

    printf("Course:\tC Programming\n");

    return 0;
}