#include <iostream>
using namespace std;

int main() {
    // Declare variables to store student information
    string name = "Amit";
    int age = 18;
    float marks = 85.5;

    // Display a heading using the insertion operator
    cout << "Student Information" << endl;

    // Display the student's name
    cout << "Name: " << name << endl;

    // Display the student's age
    cout << "Age: " << age << endl;

    // Display the student's marks
    cout << "Marks: " << marks << endl;

    // Indicate that the program ended successfully
    return 0;
}