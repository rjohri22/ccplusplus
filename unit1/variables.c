#include <stdio.h>

int main()
{
    int age = 25;              // int → data type, age → variable name, 25 → initial value

    float marks = 85.5;        // float → data type, marks → variable name

    char grade = 'A';          // char → data type, grade → variable name

    printf("Age = %d\n", age);       // Displays the value stored in age

    printf("Marks = %.1f\n", marks); // Displays the value stored in marks

    printf("Grade = %c\n", grade);   // Displays the value stored in grade

    return 0;
}