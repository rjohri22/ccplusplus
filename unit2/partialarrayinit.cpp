#include <iostream>
using namespace std;

int main()
{
    // Declare and initialize an integer array.
    int numbers[5] = {10, 20, 30};

    // Loop through all 5 elements of the array.
    for (int i = 0; i < 5; i++)
    {
        // Display the current array element.
        cout << numbers[i] << endl;
    }

    return 0;
}